/** 判断通道是否为已登记的广播事件（主进程 send / 渲染端 on 只应使用这些） */
export function isRegisteredBroadcastChannel(channel: string): boolean {
  return (IPC_BROADCAST_CHANNELS as readonly string[]).includes(channel)
}

export type IpcChannel = (typeof IPC_CHANNELS)[number];

/** 判断通道是否在清单内 */
export function isRegisteredIpcChannel(channel: string): boolean {
  return (IPC_CHANNELS as readonly string[]).includes(channel);
}

